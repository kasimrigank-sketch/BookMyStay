/**
 * Hotel Booking Management System
 * 
 * This class represents the entry point of the Book My Stay application.
 * It demonstrates how a Java application starts execution and prints
 * a welcome message to the console.
 * 
 * @author MRIGANK
 * @version 1.0
 */

public class UseCase1HotelBookingApp {

    /**
     * Main method - Entry point of the Java application
     * JVM starts execution from this method.
     *
     * @param args Command line arguments
     */
    public static void main(String[] args) {

        // Printing welcome message to console
        System.out.println("=================================");
        System.out.println(" Welcome to Book My Stay App ");
        System.out.println(" Hotel Booking Management System ");
        System.out.println(" Version: 1.0 ");
        System.out.println("=================================");

        // Application startup message
        System.out.println("Application started successfully!");

        // End of program
        System.out.println("Thank you for using Book My Stay.");
    }
}
